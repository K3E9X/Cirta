import { describe, expect, it } from 'vitest';
import { strToU8, zipSync } from 'fflate';
import { PDFDocument } from 'pdf-lib';
import { inspectFile, type Finding } from '../src/core/index.js';
import { translateLabel, translateValue } from '../src/shared/french.js';
import { legacyOffice } from './helpers/ole.js';

/*
 * [R6] Three findings the repasse of 19/10/2026 saw reported as someone's
 * identity: a .doc's AppVersion, a library's default author, an XML entity
 * nobody expanded. Each test also keeps the real case firing.
 */

const W = 'xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"';
const core = (inner: string, dtd = '') =>
  `<?xml version="1.0"?>${dtd}<cp:coreProperties xmlns:cp="http://schemas.openxmlformats.org/package/2006/metadata/core-properties" xmlns:dc="http://purl.org/dc/elements/1.1/">${inner}</cp:coreProperties>`;
const docx = (coreXml: string, extra: Record<string, string> = {}) =>
  zipSync({
    '[Content_Types].xml': strToU8('<Types/>'),
    '_rels/.rels': strToU8('<Relationships/>'),
    'docProps/core.xml': strToU8(coreXml),
    'word/document.xml': strToU8(`<w:document ${W}><w:body><w:p><w:r><w:t>Texte</w:t></w:r></w:p></w:body></w:document>`),
    ...Object.fromEntries(Object.entries(extra).map(([k, v]) => [k, strToU8(v)])),
  });
const at = (findings: Finding[], label: string) => findings.filter((f) => f.label === label);
const identity = (findings: Finding[]) => findings.filter((f) => f.kind === 'identity').map((f) => `${f.label}: ${f.value}`);

describe('[R6.1] an OLE2 property set’s AppVersion is bookkeeping', () => {
  it('is informational provenance in a .doc and a .xls; a custom property that names a client is still identity', async () => {
    for (const kind of ['doc', 'xls'] as const) {
      const { findings } = await inspectFile(legacyOffice(kind, { summary: { 4: 'Jean Dupont' }, custom: { AppVersion: '16.0000', DocSecurity: '0', Client: 'ACME' } }), `ancien.${kind}`);
      expect(identity(findings)).toEqual(expect.arrayContaining(['Author: Jean Dupont', 'Custom property: Client: ACME']));
      expect(identity(findings).some((f) => f.includes('AppVersion') || f.includes('DocSecurity'))).toBe(false);
      expect(at(findings, 'Custom property: AppVersion')[0]).toMatchObject({ kind: 'provenance', confidence: 'informational' });
    }
  });

  it('is the same in a .docx custom part', async () => {
    const custom =
      '<Properties xmlns="http://schemas.openxmlformats.org/officeDocument/2006/custom-properties" xmlns:vt="http://schemas.openxmlformats.org/officeDocument/2006/docPropsVTypes">' +
      '<property fmtid="{D5CDD505-2E9C-101B-9397-08002B2CF9AE}" pid="2" name="AppVersion"><vt:lpwstr>16.0000</vt:lpwstr></property></Properties>';
    const { findings } = await inspectFile(docx(core(''), { 'docProps/custom.xml': custom }), 'a.docx');
    expect(at(findings, 'Custom property: AppVersion')[0]).toMatchObject({ kind: 'provenance', confidence: 'informational' });
  });
});

describe('[R6.2] a library’s defaults are its mark, not a person', () => {
  it('python-docx: author, last modified by, title and description', async () => {
    const { findings } = await inspectFile(
      docx(core('<dc:title>Word Document</dc:title><dc:creator>python-docx</dc:creator><cp:lastModifiedBy>python-docx</cp:lastModifiedBy><dc:description>generated by python-docx</dc:description>')),
      'rapport.docx',
    );
    expect(identity(findings)).toEqual([]);
    const author = at(findings, 'Author')[0]!;
    expect(author).toMatchObject({ kind: 'provenance', confidence: 'informational', value: 'python-docx — the default value of python-docx' });
    expect(translateValue(author, 'fr')).toBe('python-docx — valeur par défaut de python-docx');
    // The library itself is still named.
    expect(at(findings, 'Document generated programmatically')).toHaveLength(1);
  });

  it('openpyxl', async () => {
    const xlsx = zipSync({
      '[Content_Types].xml': strToU8('<Types/>'),
      '_rels/.rels': strToU8('<Relationships/>'),
      'docProps/core.xml': strToU8(core('<dc:creator>openpyxl</dc:creator>')),
      'xl/workbook.xml': strToU8('<workbook/>'),
    });
    const { findings } = await inspectFile(xlsx, 'tableau.xlsx');
    expect(identity(findings)).toEqual([]);
    expect(at(findings, 'Author')[0]?.value).toBe('openpyxl — the default value of openpyxl');
  });

  it('ReportLab: anonymous, untitled, unspecified', async () => {
    const pdf = await PDFDocument.create();
    pdf.addPage();
    pdf.setAuthor('anonymous');
    pdf.setTitle('untitled');
    pdf.setSubject('unspecified');
    pdf.setCreator('ReportLab PDF Library - www.reportlab.com');
    pdf.setProducer('ReportLab PDF Library - www.reportlab.com');
    const { findings } = await inspectFile(await pdf.save(), 'facture.pdf');
    expect(identity(findings)).toEqual([]);
    expect(at(findings, 'Subject')[0]?.value).toBe('unspecified — the default value of ReportLab');
  });

  it('a real author in a ReportLab file, and "anonymous" without ReportLab, stay as they are', async () => {
    const named = await PDFDocument.create();
    named.addPage();
    named.setAuthor('Jeanne Martin');
    named.setProducer('ReportLab PDF Library - www.reportlab.com');
    expect(identity((await inspectFile(await named.save(), 'a.pdf')).findings)).toContain('Author: Jeanne Martin');
    const bare = await PDFDocument.create();
    bare.addPage();
    bare.setAuthor('anonymous');
    bare.setProducer('Writer 7');
    expect(identity((await inspectFile(await bare.save(), 'b.pdf')).findings)).toContain('Author: anonymous');
  });
});

describe('[R6.3] unresolved XML entities', () => {
  const DTD = '<!DOCTYPE lolz [<!ENTITY lol "lol"><!ENTITY lol2 "&lol;&lol;"><!ENTITY lol9 "&lol2;&lol2;"><!ENTITY xxe SYSTEM "file:///etc/passwd">]>';

  it('are not reported as an author or a title; the DTD is, probable, with the file an external one names', async () => {
    const { findings } = await inspectFile(docx(core('<dc:creator>&xxe;</dc:creator><dc:title>&lol9;</dc:title>', DTD)), 'bombe.docx');
    expect(identity(findings)).toEqual([]);
    const dtd = at(findings, 'DTD with entities in an XML part (unresolved)');
    expect(dtd).toEqual([{ kind: 'active-content', confidence: 'probable', location: 'docProps/core.xml', label: 'DTD with entities in an XML part (unresolved)', value: 'lol, lol2, lol9, xxe = file:///etc/passwd' }]);
    expect(translateLabel(dtd[0]!.label, 'fr')).toBe('DTD avec entités dans une partie XML (non résolues)');
  });

  it('an author written with the predefined entities is still an author', async () => {
    const { findings } = await inspectFile(docx(core('<dc:creator>Martin &amp; Fils</dc:creator>')), 'a.docx');
    expect(identity(findings)).toContain('Author: Martin & Fils');
  });
});
