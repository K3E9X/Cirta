/**
 * [R6] What a document library writes when nobody tells it otherwise.
 *
 * python-docx names the author "python-docx" and titles the file "Word
 * Document"; openpyxl signs "openpyxl"; ReportLab fills a PDF with
 * "anonymous", "untitled" and "unspecified". Reported as identity, these read
 * as a person and a subject the document does not have. They are the
 * library's mark: provenance, informational, with the library named. The
 * placeholders that could be anyone's ("anonymous") count only when the
 * library is otherwise seen in the same file.
 *
 * [R6] An XML entity left unresolved — `&xxe;`, `&lol9;` — is not a name
 * either. Ciirta never expands entities (that is the attack); a field whose
 * value is nothing but references is not reported as identity. The DTD that
 * declared them is reported on its own (xml.ts dtdFindings).
 */

import type { Finding } from './types.js';

interface Library {
  name: string;
  /** Seen somewhere in the file's findings: the library wrote it. */
  evidence: RegExp;
  /** Field label and the value the library writes into it. */
  values: Array<[string, string]>;
}

const LIBRARIES: Library[] = [
  {
    name: 'python-docx',
    evidence: /python-docx/i,
    values: [['Author', 'python-docx'], ['Last modified by', 'python-docx'], ['Title', 'Word Document'], ['Description', 'generated by python-docx']],
  },
  { name: 'python-pptx', evidence: /python-pptx/i, values: [['Author', 'python-pptx'], ['Last modified by', 'python-pptx'], ['Title', 'PowerPoint Presentation']] },
  { name: 'openpyxl', evidence: /openpyxl/i, values: [['Author', 'openpyxl'], ['Last modified by', 'openpyxl']] },
  { name: 'ReportLab', evidence: /reportlab/i, values: [['Author', 'anonymous'], ['Title', 'untitled'], ['Subject', 'unspecified']] },
];

/** The marker the French report translates: « … — valeur par défaut de … ». */
export const DEFAULT_OF = ' — the default value of ';

/** Only references to entities, beside the five XML predefines and character references. */
const UNRESOLVED = /^(?:\s*&(?!(?:amp|lt|gt|quot|apos);)[A-Za-z_][\w.-]*;)+\s*$/;

export function libraryDefaults(findings: Finding[]): Finding[] {
  const seen = LIBRARIES.filter((library) => findings.some((f) => library.evidence.test(f.value)));
  return findings
    .filter((f) => !(f.kind === 'identity' && UNRESOLVED.test(f.value)))
    .map((f) => {
      if (f.kind !== 'identity') return f;
      const library = seen.find((l) => l.values.some(([label, value]) => label === f.label && value.toLowerCase() === f.value.trim().toLowerCase()));
      return library ? { ...f, kind: 'provenance', confidence: 'informational', value: `${f.value}${DEFAULT_OF}${library.name}` } : f;
    });
}
